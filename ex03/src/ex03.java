public class ex03 {
    static void main(String[] args){

        int a = 0b1011; // 0b = 이진수
        int b = 0732; // 0 = 8진수
        int c = 365;
        int d = 0xa29; // 0x = 10진수
        System.out.println("a = " + a);
        System.out.println("b = " + b);
        System.out.println("c = " + c);
        System.out.println("d = " + d);
    }
}

